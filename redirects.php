function alif_seo_redirects() {
    if (is_admin() || wp_doing_ajax() || (defined('REST_REQUEST') && REST_REQUEST)) {
        return;
    }
    $path = (string) wp_parse_url($_SERVER['REQUEST_URI'] ?? '', PHP_URL_PATH);
    $path = '/' . trim($path, '/') . '/';
    $map = alif_seo_redirect_map();
    if (isset($map[$path])) {
        wp_safe_redirect(home_url($map[$path]), 301, 'Alif SEO');
        exit;
    }
}
add_action('template_redirect', 'alif_seo_redirects', 1);
